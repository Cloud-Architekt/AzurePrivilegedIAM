    // ---- Graph build -----------------------------------------------------
    tierRank: function (name) {
        var i = EOCE.TIER_ORDER.indexOf(name);
        return i < 0 ? 99 : i;
    },

    buildGraph: function (paths, activeCols) {
        var self = this;
        var nodeMap = {};
        var linkMap = {};

        function ensureNode(colKey, p) {
            var col = self.COLUMNS[colKey];
            var id = col.id(p);
            if (!nodeMap[id]) {
                nodeMap[id] = {
                    id: id,
                    name: col.name(p),
                    tier: col.tier(p),
                    kind: col.kind,
                    meta: col.meta ? col.meta(p) : null,
                    column: colKey,
                    _rank: undefined
                };
            }
            return id;
        }

        paths.forEach(function (p) {
            var ids = activeCols.map(function (c) { return ensureNode(c, p); });
            // Aggregate the highest-privilege tier flowing through service/system nodes.
            activeCols.forEach(function (c, idx) {
                var n = nodeMap[ids[idx]];
                if (n.kind === 'service' || n.kind === 'system') {
                    var r = self.tierRank(p.tier);
                    if (n._rank === undefined || r < n._rank) { n._rank = r; n.tier = EOCE.TIER_ORDER[r]; }
                }
            });
            for (var i = 0; i < ids.length - 1; i++) {
                var key = ids[i] + '\u2192' + ids[i + 1];
                var link = linkMap[key];
                if (!link) {
                    link = { source: ids[i], target: ids[i + 1], value: 0, rank: 99 };
                    linkMap[key] = link;
                }
                link.value += 1;
                var lr = self.tierRank(p.tier);
                if (lr < link.rank) link.rank = lr;
            }
        });

        var nodes = Object.keys(nodeMap).map(function (k) { return nodeMap[k]; });
        var index = {};
        nodes.forEach(function (n, i) { index[n.id] = i; });
        var links = Object.keys(linkMap).map(function (k) {
            var l = linkMap[k];
            return { source: index[l.source], target: index[l.target], value: l.value, rank: l.rank };
        });
        return { nodes: nodes, links: links };
    },

    nodeColor: function (n) {
        if (n.tier && EOCE.TIERS[n.tier]) return EOCE.tier(n.tier).color;
        return '#8b949e';
    },

    // ---- Draw ------------------------------------------------------------
    draw: function () {
        var self = this;
        var empty = document.getElementById('tmEmpty');
        var svg = document.getElementById('tmSankey');
        var mode = this.state.viewMode || 'sankey';

        var d3Ready = typeof d3 !== 'undefined';
        var sankeyReady = d3Ready && typeof d3.sankey !== 'undefined';
        if (!d3Ready || (mode === 'sankey' && !sankeyReady)) {
            svg.innerHTML = '';
            empty.style.display = '';
            empty.innerHTML = 'The visualization library could not be loaded. The EAM Map needs the d3 / d3-sankey scripts ' +
                'in <code>assets/vendor/</code> (referenced from index.html). Make sure those files are present, or browse the data via the ' +
                '<a href="#roles">Roles</a> and <a href="#actions">Role Actions</a> views.';
            this.renderStats([]);
            this.renderContrib();
            return;
        }

        this._clearHighlight = null;
        this._focusMark = null;
        var paths = this.filteredPaths();
        this.renderStats(paths);
        d3.select(svg).selectAll('*').remove();
        svg.innerHTML = '';
        svg.removeAttribute('viewBox');
        svg.removeAttribute('style');

        if (!paths.length) {
            empty.style.display = '';
            empty.textContent = 'No classification data matches the current filters.';
            this.renderContrib();
            return;
        }

        var drew;
        if (mode === 'icicle') drew = this.drawIcicle(paths);
        else if (mode === 'treemap') drew = this.drawTreemap(paths);
        else if (mode === 'heatmap') drew = this.drawHeatmap(paths);
        else drew = this.drawSankeyMode(paths);

        this.renderContrib();

        if (drew !== false && this.pendingFocus) {
            var pf = this.pendingFocus; this.pendingFocus = null;
            this.applyPendingFocus(pf, mode);
        }
    },

    applyPendingFocus: function (pf, mode) {
        if (mode === 'sankey') { this.focusNode(pf.id); return; }
        // For hierarchy/heatmap modes, focus the contributing-actions table and
        // visually emphasise the matching marks.
        var label = pf.id;
        // Derive candidate ids via COLUMNS so the lookup matches the real node id
        // shape (action ids include the action type segment).
        var col = this.COLUMNS[pf.column];
        var match = (this.paths || []).find(function (p) {
            return col.id(p) === pf.id;
        });
        if (match) label = pf.column === 'role' ? match.role : match.action;
        this.state.tableFilter = { column: pf.column, id: pf.id, label: label };
        this.renderContrib();
        if (this._focusMark) this._focusMark(pf.id);
        var wrap = document.querySelector('.tm-diagram-wrap');
        if (wrap && wrap.scrollIntoView) wrap.scrollIntoView({ behavior: 'smooth', block: 'start' });
    },

