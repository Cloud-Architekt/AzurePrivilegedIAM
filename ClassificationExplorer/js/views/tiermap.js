                'Switch between a <strong>Sankey</strong> flow, a zoomable <strong>icicle</strong>, a <strong>treemap</strong>, or a roles &times; services <strong>heatmap</strong>. ' +
                'Filter by system, service, privileged roles, or use the mismatch filter to focus on role actions that differ between the live definition and the Microsoft Learn reference.</p></div>' +
                '<div id="tmToolbar"></div>' +
                '<div id="tmLegend" class="tm-legend"></div>' +
                '<div id="tmStats" class="tm-stats"></div>' +
                '<div class="tm-diagram-wrap"><div id="tmEmpty" class="tm-empty" style="display:none;"></div><svg id="tmSankey"></svg></div>' +
                '<div class="tm-contrib">' +
                '<div class="tm-contrib-head"><div class="section-title" style="margin:0;">Contributing role actions</div>' +
                '<span id="tmFocusTag" class="chip" style="display:none;"></span>' +
                '<button id="tmClearFocus" class="btn small" type="button" style="display:none;">Clear selection</button>' +
                '<span class="toolbar-meta" id="tmContribCount"></span></div>' +
                '<p class="muted" style="margin:2px 0 10px;font-size:12px;">Click any node in the diagram to focus this list on the role actions flowing through it &mdash; this is the "why" behind a tier classification.</p>' +
                '<div class="table-wrap"><table class="grid-table" id="tmContribTable"></table></div></div>' +
                '</div>';

            self.tooltip = document.getElementById('tmTooltip');
            if (!self.tooltip) {
                self.tooltip = document.createElement('div');
                self.tooltip.id = 'tmTooltip';
                self.tooltip.className = 'tm-tooltip';
                self.tooltip.style.display = 'none';
                document.body.appendChild(self.tooltip);
                // The tooltip is appended to <body>, so it outlives this view - hide it
                // on any navigation so it can't linger over another view.
                window.addEventListener('hashchange', function () { self.tooltip.style.display = 'none'; });
            }
            self.tooltip.style.display = 'none';

            // Deep-link focus: #overview/role/<sys>/<roleId> or #overview/action/<sys>/<action>/<actionType>
            self.pendingFocus = null;
            // Re-rendering without focus params ends a previous deep-link focus, so
            // restore the systems selection scopeToFocus narrowed (see scopeToFocus).
            if (self.state.linkFocus && self._preFocusSystems) {
                self.state.systems = self._preFocusSystems;
                self._preFocusSystems = null;
            }
            self.state.linkFocus = null;
