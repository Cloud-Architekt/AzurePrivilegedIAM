    // a display name, a tier (for colouring) and the node "kind".
    COLUMNS: {
        system: {
            label: 'Role system', kind: 'system',
            id: function (p) { return 'SY:' + p.sys; },
            name: function (p) { return (EOCE.RBAC_SYSTEMS[p.sys] || {}).short || p.sys; },
            tier: function () { return null; }
        },
        role: {
            label: 'Role', kind: 'role',
            id: function (p) { return 'R:' + p.sys + '|' + p.roleId; },
            name: function (p) { return p.role; },
            tier: function (p) { return p.roleClass; },
            meta: function (p) { return (EOCE.RBAC_SYSTEMS[p.sys] || {}).short || p.sys; }
        },
        service: {
            label: 'Service', kind: 'service',
            id: function (p) { return 'SV:' + p.sys + '|' + p.service; },
            name: function (p) { return p.service; },
            tier: function () { return null; }
        },
        action: {
            label: 'Role action', kind: 'action',
            id: function (p) { return 'A:' + p.sys + '|' + (p.actionType === 'DataAction' ? 'DataAction' : 'Action') + '|' + p.action; },
            name: function (p) { return p.action; },
            tier: function (p) { return p.tier; }
        },
        tier: {
            label: 'Tier level', kind: 'tier',
            id: function (p) { return 'T:' + p.tier; },
            name: function (p) { return EOCE.tier(p.tier).label; },
            tier: function (p) { return p.tier; }
        }
    },
    COLUMN_ORDER: ['system', 'role', 'service', 'action', 'tier'],
    DEFAULT_COLUMNS: ['role', 'service', 'tier'],
    NODE_CAP: 900,

    // Selectable visualizations. They all share the same filters, stats, legend,
    // deep-link focus and the contributing-actions table below the chart.
    VIEW_MODES: [
        { key: 'sankey', label: 'Sankey', hint: 'Flow of role \u2192 service \u2192 action \u2192 tier' },
        { key: 'icicle', label: 'Icicle', hint: 'Zoomable space-filling hierarchy' },
        { key: 'treemap', label: 'Treemap', hint: 'Area = number of role actions' },
        { key: 'heatmap', label: 'Heatmap', hint: 'Roles \u00d7 services, coloured by highest tier' }
    ],
    HEATMAP_CELL_CAP: 20000,

    state: null,

    // ---- Lifecycle -------------------------------------------------------
