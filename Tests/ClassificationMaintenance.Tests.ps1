#Requires -Modules Pester

BeforeAll {
    $script:RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
    $script:PrivateRoot = Join-Path $script:RepositoryRoot 'Modules/EntraOps.Classification/Private'
    $script:PublicRoot = Join-Path $script:RepositoryRoot 'Modules/EntraOps.Classification/Public'
    . (Join-Path $script:PrivateRoot 'Resolve-EntraOpsClassificationRepoRoot.ps1')
    . (Join-Path $script:PrivateRoot 'Get-EntraOpsRoleDefinitionOverwrites.ps1')
    . (Join-Path $script:PublicRoot 'Export-EntraOpsClassificationDirectoryRolesFromMsftDocs.ps1')
}

Describe 'Classification maintenance source resolution' {
    It 'resolves the source checkout from either module layout' {
        $root = Join-Path $TestDrive 'Coding'
        $source = Join-Path $root 'AzurePrivilegedIAM'
        $target = Join-Path $root 'EntraOps'
        New-Item -ItemType Directory -Force -Path "$source/Classification", "$source/EntraOps_Classification", "$source/Modules/EntraOps.Classification", "$target/Classification", "$target/Reports/ClassificationExplorer", "$target/EntraOps" | Out-Null

        Resolve-EntraOpsClassificationRepoRoot -ModuleBase "$source/Modules/EntraOps.Classification" | Should -Be $source
        Resolve-EntraOpsClassificationRepoRoot -ModuleBase "$target/EntraOps" | Should -Be $source
        New-Item -ItemType Directory -Force -Path "$root/AzurePrivilegedIAM-other/Classification", "$root/AzurePrivilegedIAM-other/EntraOps_Classification" | Out-Null
        { Resolve-EntraOpsClassificationRepoRoot -ModuleBase "$target/EntraOps" } | Should -Throw '*Pass -RepoRoot explicitly*'
    }
}

Describe 'Documentation exporter owner-scoped permissions' {
    It 'excludes owned sections, nested subsections and owner-conditioned rows, then resumes tenant actions' {
        $classification = Join-Path $TestDrive 'classification.json'
        $output = Join-Path $TestDrive 'roles.json'
        Set-Content -LiteralPath $classification -Value '[]'
        Mock Invoke-WebRequest {
            if ($Uri -eq 'https://example.test/reference.md') {
                return [pscustomobject]@{ Content = @'
| [Example role](#example-role) | Example | 55555555-5555-5555-5555-555555555555 |
[!INCLUDE [example-role](includes/example-role.md)]
'@ }
            }
            return [pscustomobject]@{ Content = @'
---
title: Example role
---
<!-- autogenerated content starts here -->
## Tenant actions
| Actions | Description |
| --- | --- |
| microsoft.directory/users/read | Tenant read |
> ## Owned application registrations
> | microsoft.directory/applications/delete | Owner only |
> ### Nested section
> | microsoft.directory/applications/create | Still owner only |
## Other tenant actions
| microsoft.directory/groups/read | Tenant read |
| microsoft.directory/applications/update | Condition: $SubjectIsOwner |
## SubjectIsOwner actions
| microsoft.directory/servicePrincipals/delete | Owner only |
## Final tenant actions
| microsoft.directory/devices/read | Tenant read |
'@ }
        }

        Export-EntraOpsClassificationDirectoryRolesFromMsftDocs -PermissionsReferenceUri 'https://example.test/reference.md' -ClassificationFilePath $classification -OutputFilePath $output -RoleDefinitionOverwritesFilePath (Join-Path $TestDrive 'missing.json') | Out-Null
        $role = @(Get-Content -LiteralPath $output -Raw | ConvertFrom-Json)[0]
        @($role.RolePermissions.AuthorizedResourceAction | Sort-Object) | Should -Be @('microsoft.directory/devices/read', 'microsoft.directory/groups/read', 'microsoft.directory/users/read')
    }
}

Describe 'Module-based classification model updates' {
    BeforeAll {
        $script:FixtureModuleRoot = Join-Path $TestDrive 'FixtureModule'
        $script:SourceRoot = Join-Path $TestDrive 'ModelSource'
        New-Item -ItemType Directory -Force -Path $script:FixtureModuleRoot, "$script:SourceRoot/Classification", "$script:SourceRoot/EntraOps_Classification", "$script:SourceRoot/ClassificationExplorer" | Out-Null
        Copy-Item -LiteralPath (Join-Path $script:PublicRoot 'Update-EntraOpsClassificationModels.ps1') -Destination $script:FixtureModuleRoot
        Copy-Item -LiteralPath (Join-Path $script:PublicRoot 'Sync-EntraOpsClassificationExplorerSource.ps1') -Destination $script:FixtureModuleRoot
        $moduleText = @'
. "$PSScriptRoot/Update-EntraOpsClassificationModels.ps1"
. "$PSScriptRoot/Sync-EntraOpsClassificationExplorerSource.ps1"
function Read-Host { param($Prompt) Add-Content ./sync-prompts.txt $Prompt; Get-Content ./sync-target.txt }
$script:FixtureImportId = [guid]::NewGuid()
function Get-FixtureImportId { $script:FixtureImportId }
function Save-FixtureLane {
    param($Name)
    if (Test-Path ./parallel.txt) { Set-Content -LiteralPath "./$Name.done" -Value $Name }
    else { Add-Content ./lanes.txt $Name }
}
function Export-EntraOpsClassificationAppRoles { Save-FixtureLane 'AppRoles' }
function Export-EntraOpsClassificationScopes {
    if (Test-Path ./fail.txt) { throw 'Fixture failure' }
    if (Test-Path ./nonterminating-error.txt) { Write-Error 'Fixture nonterminating failure' }
    Save-FixtureLane 'Scopes'
}
function Export-EntraOpsClassificationApiPermissions { Save-FixtureLane 'ApiPermissions' }
function Export-EntraOpsClassificationDirectoryRoles { param($IncludeCustomRoles) Save-FixtureLane 'DirectoryRoles' }
function Export-EntraOpsClassificationDirectoryRolesFromMsftDocs { Save-FixtureLane 'Docs' }
function Get-EntraOpsClassificationDirectoryRolesMismatchFromMsftDocs { param($ShowSummaryOnly) }
function Export-EntraOpsClassificationIdentityGovernanceRoles { param($IncludeCustomRoles) Save-FixtureLane 'IdGov' }
function Export-EntraOpsClassificationDeviceManagementRoles { param($IncludeCustomRoles) Save-FixtureLane 'Intune' }
function Export-EntraOpsClassificationAzureRoles { param($IncludeCustomRoles, $ClassificationFile) Save-FixtureLane 'Azure' }
'@
        Set-Content -LiteralPath "$script:FixtureModuleRoot/AlignmentFixture.psm1" -Value $moduleText
        Import-Module "$script:FixtureModuleRoot/AlignmentFixture.psm1" -Force
    }

    AfterAll { Remove-Module AlignmentFixture -Force -ErrorAction SilentlyContinue }

    BeforeEach {
        $script:SourceRoot = Join-Path $TestDrive ([guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Force -Path "$script:SourceRoot/Classification", "$script:SourceRoot/EntraOps_Classification", "$script:SourceRoot/ClassificationExplorer" | Out-Null
    }

    It 'runs every export lane through the imported module without a Scripts folder and restores location' {
        $before = (Get-Location).Path
        $importId = Get-FixtureImportId
        $result = Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -Sequential -SkipClassificationExplorerUpdate -SkipEntraOpsRepoSync
        Get-Content "$script:SourceRoot/lanes.txt" | Should -Be @('AppRoles', 'Scopes', 'ApiPermissions', 'DirectoryRoles', 'Docs', 'IdGov', 'Intune', 'Azure')
        $result.RepoRoot | Should -Be $script:SourceRoot
        (Get-Location).Path | Should -Be $before
        Get-FixtureImportId | Should -Be $importId -Because 'reloading the caller module would reset its authentication and cache state'
    }

    It 'copies the fixed editor and regression tests to EntraOps when the update sync prompt is accepted' {
        $target = Join-Path $TestDrive 'SyncTarget'
        $sourceApp = Join-Path $script:SourceRoot 'ClassificationExplorer'
        $targetApp = Join-Path $target 'Reports/ClassificationExplorer'
        $generatorDir = Join-Path $script:SourceRoot 'Modules/EntraOps.Classification/Public'
        New-Item -ItemType Directory -Force -Path "$sourceApp/js/views", "$targetApp/js/views", "$targetApp/data", $generatorDir | Out-Null
        foreach ($relativePath in 'js/views/customize.js', 'classification-explorer-customize.spec.mjs') {
            Copy-Item -LiteralPath (Join-Path $script:RepositoryRoot "ClassificationExplorer/$relativePath") -Destination (Join-Path $sourceApp $relativePath)
            Set-Content -LiteralPath (Join-Path $targetApp $relativePath) -Value 'old source'
        }
        Copy-Item -LiteralPath (Join-Path $script:PublicRoot 'Update-EntraOpsClassificationExplorerData.ps1') -Destination $generatorDir
        Set-Content -LiteralPath "$targetApp/js/mode.js" -Value 'entraops'
        Set-Content -LiteralPath "$targetApp/data/classification-data.js" -Value 'tenant bundle'
        Set-Content -LiteralPath "$script:SourceRoot/sync-target.txt" -Value $target

        Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -Sequential -SkipClassificationExplorerUpdate | Out-Null

        @(Get-Content -LiteralPath "$script:SourceRoot/sync-prompts.txt").Count | Should -Be 1
        foreach ($relativePath in 'js/views/customize.js', 'classification-explorer-customize.spec.mjs') {
            Get-Content -LiteralPath (Join-Path $targetApp $relativePath) -Raw |
                Should -Be (Get-Content -LiteralPath (Join-Path $sourceApp $relativePath) -Raw)
        }
        (Get-Content -LiteralPath "$targetApp/js/mode.js" -Raw).Trim() | Should -Be 'entraops'
        (Get-Content -LiteralPath "$targetApp/data/classification-data.js" -Raw).Trim() | Should -Be 'tenant bundle'
    }

    It 'surfaces an export failure and restores the caller location' {
        $before = (Get-Location).Path
        Set-Content -LiteralPath "$script:SourceRoot/fail.txt" -Value 'fail'
        { Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -Sequential -SkipClassificationExplorerUpdate -SkipEntraOpsRepoSync } | Should -Throw '*Scopes failed: Fixture failure*'
        (Get-Location).Path | Should -Be $before
    }

    It 'waits for all parallel lanes without reloading the caller module' {
        Set-Content -LiteralPath "$script:SourceRoot/parallel.txt" -Value 'parallel'
        $before = (Get-Location).Path
        $importId = Get-FixtureImportId
        $result = Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -SkipClassificationExplorerUpdate -SkipEntraOpsRepoSync
        @(Get-ChildItem -LiteralPath $script:SourceRoot -Filter '*.done').Count | Should -Be 8
        $result.RepoRoot | Should -Be $script:SourceRoot
        (Get-Location).Path | Should -Be $before
        Get-FixtureImportId | Should -Be $importId
    }

    It 'reports the original parallel lane failure and cleans up jobs under ErrorAction Stop' {
        Set-Content -LiteralPath "$script:SourceRoot/parallel.txt" -Value 'parallel'
        Set-Content -LiteralPath "$script:SourceRoot/fail.txt" -Value 'fail'
        $before = (Get-Location).Path
        $existingJobs = @(Get-Job | Select-Object -ExpandProperty Id)
        { Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -SkipClassificationExplorerUpdate -SkipEntraOpsRepoSync -ErrorAction Stop } | Should -Throw '*ApiPermissions: Scopes failed: Fixture failure*'
        @(Get-Job | Where-Object { $_.Id -notin $existingJobs }).Count | Should -Be 0
        (Get-Location).Path | Should -Be $before
    }

    It 'rejects nonterminating export errors with Sequential=<Sequential>' -ForEach @(
        @{ Sequential = $true }, @{ Sequential = $false }
    ) {
        Set-Content -LiteralPath "$script:SourceRoot/parallel.txt" -Value 'parallel'
        Set-Content -LiteralPath "$script:SourceRoot/nonterminating-error.txt" -Value 'fail'
        { Update-EntraOpsClassificationModels -RepoRoot $script:SourceRoot -Sequential:$Sequential -SkipClassificationExplorerUpdate -SkipEntraOpsRepoSync } | Should -Throw '*Scopes failed: Fixture nonterminating failure*'
    }
}
